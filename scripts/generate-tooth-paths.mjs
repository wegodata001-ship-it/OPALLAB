/**
 * Symmetric dental-arch placement (11↔21 / 41↔31 at apex).
 * Shapes live in ToothShape.tsx.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

function toothKind(n) {
  const d = n % 10;
  if (d === 1 || d === 2) return "incisor";
  if (d === 3) return "canine";
  if (d === 4 || d === 5) return "premolar";
  return "molar";
}

function archTeeth(ids, { cx, cy, rx, ry, openDown }) {
  const n = ids.length;
  return ids.map((id, i) => {
    // Equal parametric steps keep perfect left/right symmetry
    const t = i / (n - 1);
    const angle = Math.PI * (1 - t);
    const x = cx + rx * Math.cos(angle);
    const y = openDown ? cy - ry * Math.sin(angle) : cy + ry * Math.sin(angle);

    const tx = -Math.sin(angle);
    const ty = openDown ? -Math.cos(angle) : Math.cos(angle);
    const rotation = (Math.atan2(ty, tx) * 180) / Math.PI + 90;

    return {
      number: id,
      jaw: id < 30 ? "upper" : "lower",
      side: [1, 4].includes(Math.floor(id / 10)) ? "right" : "left",
      kind: toothKind(id),
      cx: +x.toFixed(2),
      cy: +y.toFixed(2),
      rotation: +rotation.toFixed(2),
    };
  });
}

const upperIds = [18, 17, 16, 15, 14, 13, 12, 11, 21, 22, 23, 24, 25, 26, 27, 28];
const lowerIds = [48, 47, 46, 45, 44, 43, 42, 41, 31, 32, 33, 34, 35, 36, 37, 38];

/* Compact arch — teeth sit close, large crowns (~+25%) still fit without overlap */
const UPPER_TEETH = archTeeth(upperIds, {
  cx: 240,
  cy: 270,
  rx: 198,
  ry: 205,
  openDown: true,
});

const LOWER_TEETH = archTeeth(lowerIds, {
  cx: 240,
  cy: 50,
  rx: 198,
  ry: 205,
  openDown: false,
});

const out = `/* Auto-generated by scripts/generate-tooth-paths.mjs — do not edit by hand */
import type { ToothDefinition } from "./toothTypes";

export const UPPER_TEETH: ToothDefinition[] = ${JSON.stringify(UPPER_TEETH, null, 2)};

export const LOWER_TEETH: ToothDefinition[] = ${JSON.stringify(LOWER_TEETH, null, 2)};

export const ALL_TEETH: ToothDefinition[] = [...UPPER_TEETH, ...LOWER_TEETH];

export const UPPER_JAW_NUMBERS = UPPER_TEETH.map((t) => t.number);
export const LOWER_JAW_NUMBERS = LOWER_TEETH.map((t) => t.number);
export const RIGHT_SIDE_NUMBERS = [18, 17, 16, 15, 14, 13, 12, 11, 48, 47, 46, 45, 44, 43, 42, 41];
export const LEFT_SIDE_NUMBERS = [21, 22, 23, 24, 25, 26, 27, 28, 31, 32, 33, 34, 35, 36, 37, 38];
export const ALL_TOOTH_NUMBERS = ALL_TEETH.map((t) => t.number);

export const UPPER_VIEWBOX = "0 0 480 320";
export const LOWER_VIEWBOX = "0 0 480 320";
`;

const dest = join(__dirname, "..", "src", "components", "DentalChart", "toothData.ts");
writeFileSync(dest, out, "utf8");

