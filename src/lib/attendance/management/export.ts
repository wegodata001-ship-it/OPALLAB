import { formatDate, formatTime } from "@/lib/utils";
import { USER_ROLE_LABELS } from "@/lib/constants/labels";
import type { AttendanceManagementRecord } from "@/lib/attendance/management/types";
import { ANOMALY_LABELS } from "@/lib/attendance/management/status";
import { getAttendanceStatus, formatDurationFromHours } from "@/lib/attendance/management/attendance-status";

function complianceLabel(r: AttendanceManagementRecord): string {
  return getAttendanceStatus(r).label;
}

function anomaliesLabel(r: AttendanceManagementRecord): string {
  return r.anomalies.map((a) => ANOMALY_LABELS[a]).join(", ");
}

function escapeCsv(value: string | number | null | undefined): string {
  const s = value == null ? "" : String(value);
  if (s.includes(",") || s.includes('"') || s.includes("\n")) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

function formatDuration(record: AttendanceManagementRecord): string {
  if (record.durationHours != null) return formatDurationFromHours(record.durationHours);
  if (!record.checkOut) return "פתוח";
  return "—";
}

/** CSV export only. PDF is generated by `/api/attendance/pdf`. */
export function buildAttendanceExport(
  records: AttendanceManagementRecord[],
  format: string,
): { body: string; contentType: string; filename: string } {
  if (format !== "csv") {
    throw new Error("PDF export moved to /api/attendance/pdf");
  }

  const stamp = formatDate(new Date()).replace(/\//g, "-");
  const headers = [
    "שם",
    "תפקיד",
    "טלפון",
    "תאריך",
    "כניסה",
    "יציאה",
    "משך (HH:mm)",
    "סטטוס",
    "חריגות",
    "ערוץ",
    "כתובת כניסה",
    "כתובת יציאה",
    "GPS כניסה",
    "GPS יציאה",
    "IP",
    "מכשיר",
  ];
  const lines = records.map((r) =>
    [
      r.employee.name,
      USER_ROLE_LABELS[r.employee.role],
      r.employee.phone ?? "",
      formatDate(r.checkIn),
      formatTime(r.checkIn),
      r.checkOut ? formatTime(r.checkOut) : "",
      formatDuration(r),
      complianceLabel(r),
      anomaliesLabel(r),
      r.channelLabel,
      r.checkInAddress ?? "",
      r.checkOutAddress ?? "",
      r.checkInLatitude != null && r.checkInLongitude != null
        ? `${r.checkInLatitude},${r.checkInLongitude}`
        : "",
      r.checkOutLatitude != null && r.checkOutLongitude != null
        ? `${r.checkOutLatitude},${r.checkOutLongitude}`
        : "",
      r.ipAddress ?? "",
      r.checkInDeviceType ?? r.deviceInfo ?? "",
    ]
      .map(escapeCsv)
      .join(","),
  );
  const body = "\uFEFF" + [headers.join(","), ...lines].join("\n");
  return {
    body,
    contentType: "text/csv;charset=utf-8",
    filename: `attendance-${stamp}.csv`,
  };
}
